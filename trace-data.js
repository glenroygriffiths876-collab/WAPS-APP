export const TRACE_UPPER='ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');
export const TRACE_LOWER='abcdefghijklmnopqrstuvwxyz'.split('');
export const TRACE_DIGITS='0123456789'.split('');
export const TRACE_REQUIRED=[...TRACE_UPPER,...TRACE_LOWER,...TRACE_DIGITS];
export function validateTraceGlyphs(){
 const errors=[];
 for(const key of TRACE_REQUIRED){
   const g=TRACE_GLYPHS[key];
   if(!g||!Array.isArray(g.strokes)||!g.strokes.length){errors.push(key+': missing strokes');continue}
   g.strokes.forEach((s,i)=>{if(!s.d||!/^[MLCQ]/.test(s.d))errors.push(key+': stroke '+(i+1)+' invalid path')});
 }
 return errors;
}
